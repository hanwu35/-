CREATE PROCEDURE InitializeUrgentQuotas()
BEGIN
    DECLARE current_date DATE;
    DECLARE i INT DEFAULT 0;
    DECLARE time_slots_count INT;
    DECLARE j INT DEFAULT 0;
    -- 获取所有时间段
    DECLARE CONTINUE HANDLER FOR NOT FOUND SET j = -1;
    -- 初始化未来7天的加急名额
    WHILE i < 7 DO
            SET current_date = DATE_ADD(CURDATE(), INTERVAL i DAY);
            -- 为每个时间段初始化名额
            INSERT INTO urgent_quotas (quota_date, time_slot, total_limit, used_count)
            SELECT
                        current_date,
                        sd.time_slot,
                        100,
                        0
            FROM shift_definitions sd
            ON DUPLICATE KEY UPDATE
                                 total_limit = 100,
                                 used_count = used_count; -- 如果已存在，保留已使用的数量
            SET i = i + 1;
        END WHILE;
END //
DELIMITER ;

-- 执行初始化
CALL InitializeUrgentQuotas();

